#!/usr/bin/env node
// Generates tokens.css from tokens.json. Never edit tokens.css by hand.
//
//   node brand/tokens/build-tokens.mjs           # write tokens.css
//   node brand/tokens/build-tokens.mjs --check   # exit 1 if tokens.css is stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { here, tokens, resolve } from "./lib.mjs";

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const lines = [];
const v = (name, value) => lines.push(`  --${name}: ${value};`);

// Fixed palette: the same in both modes. A token is a colour, not a role.
for (const [group, entries] of Object.entries(tokens.color)) {
  if (["status", "diagram"].includes(group)) continue;
  for (const key of Object.keys(entries)) {
    v(key === "DEFAULT" ? group : `${group}-${kebab(key)}`, resolve(key === "DEFAULT" ? group : `${group}.${key}`));
  }
}
v("font-sans", tokens.font.sans.value);
v("font-mono", tokens.font.mono.value);
for (const [k, r] of Object.entries(tokens.shape.radius)) v(`radius-${k}`, r);
v("measure", tokens.type.measure);

// Role tokens: what a surface should actually use. These flip with the theme.
const roles = (mode) => {
  const dark = mode === "dark";
  const out = [];
  const r = (name, value) => out.push(`  --${name}: ${value};`);
  r("bg", dark ? "var(--ink)" : "var(--paper)");
  r("bg-raised", dark ? "var(--ink-raised)" : "var(--paper-raised)");
  r("line", dark ? "var(--ink-line)" : "var(--paper-line)");
  r("text", dark ? "var(--mist)" : "var(--paper-text)");
  r("text-dim", dark ? "var(--mist-dim)" : "var(--paper-dim)");
  r("text-muted", dark ? "var(--mist-muted)" : "var(--paper-muted)");
  r("accent", dark ? "var(--gold)" : "var(--gold-dim)");
  r("accent-text", dark ? "var(--gold-bright)" : "var(--gold-deep)");
  r("focus", dark ? "var(--gold-bright)" : "var(--gold-deep)");
  for (const [k, s] of Object.entries(tokens.color.status)) {
    if (!k.startsWith("$")) r(`status-${kebab(k)}`, s[mode]);
  }
  for (const [k, s] of Object.entries(tokens.color.diagram)) {
    if (k.startsWith("$")) continue;
    r(`diagram-${k}-fill`, s[mode].fill);
    r(`diagram-${k}-stroke`, s[mode].stroke);
  }
  return out;
};

const css = [
  "/* Generated by build-tokens.mjs from tokens.json. Do not edit by hand. */",
  "/* Dark is the default brand surface; light is opt-in or follows the viewer. */",
  ":root {",
  ...lines,
  ...roles("dark"),
  "}",
  "@media (prefers-color-scheme: light) {",
  "  :root:not([data-theme=\"dark\"]) {",
  ...roles("light").map((l) => `  ${l}`),
  "  }",
  "}",
  ":root[data-theme=\"light\"] {",
  ...roles("light"),
  "}",
  ":root[data-theme=\"dark\"] {",
  ...roles("dark"),
  "}",
  "",
].join("\n");

const target = join(here, "tokens.css");
if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== css) {
    console.error("build-tokens: tokens.css is stale; run node brand/tokens/build-tokens.mjs");
    process.exit(1);
  }
  console.log("build-tokens: tokens.css is current");
} else {
  writeFileSync(target, css);
  console.log(`build-tokens: wrote ${target}`);
}
