"""Generates the social and banner templates from the tokens and the logo drawings.
   python3 -I make-templates.py   (run from brand/templates)
Placeholders are written {{LIKE_THIS}}: replace them, keep everything else.
Text is live Inter: export to PNG from a browser or Figma with Inter installed."""
import json, re, pathlib
here = pathlib.Path(__file__).resolve().parent
T = json.loads((here.parent / "tokens" / "tokens.json").read_text())
C = T["color"]
INK, RAISED, LINE = C["ink"]["DEFAULT"]["value"], C["ink"]["raised"]["value"], C["ink"]["line"]["value"]
GOLD, BRIGHT = C["gold"]["DEFAULT"]["value"], C["gold"]["bright"]["value"]
MIST, DIM, MUTED = C["mist"]["DEFAULT"]["value"], C["mist"]["dim"]["value"], C["mist"]["muted"]["value"]
BUILT = C["status"]["inProgress"]["dark"]

def mark_inner(name, uid):
    s = (here.parent / "logos" / f"{name}.svg").read_text()
    s = s.split("</title>", 1)[1].rsplit("</svg>", 1)[0]
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    return s.replace('id="sdNodesdark"', f'id="sd{uid}"').replace("url(#sdNodesdark)", f"url(#sd{uid})")

FONT = "Inter, system-ui, sans-serif"
MONO = "'JetBrains Mono', ui-monospace, monospace"

def graph(x, y, s, uid):
    """The node-edge-check motif: six mist nodes on a ring, one gold answer node."""
    import math
    pts = [(x + s * math.cos(a), y + s * math.sin(a)) for a in [i * math.pi / 3 - math.pi / 2 for i in range(6)]]
    edges = "".join(f'<line x1="{x:.0f}" y1="{y:.0f}" x2="{px:.0f}" y2="{py:.0f}"/>' for px, py in pts)
    ring = "".join(f'<line x1="{a[0]:.0f}" y1="{a[1]:.0f}" x2="{b[0]:.0f}" y2="{b[1]:.0f}"/>' for a, b in zip(pts, pts[1:] + pts[:1]))
    nodes = "".join(f'<circle cx="{px:.0f}" cy="{py:.0f}" r="{s*0.035:.1f}" fill="{INK}" stroke="{DIM}" stroke-width="2"/>' for px, py in pts)
    return (f'<defs><radialGradient id="glow{uid}"><stop offset="0" stop-color="{GOLD}" stop-opacity=".18"/>'
            f'<stop offset="1" stop-color="{GOLD}" stop-opacity="0"/></radialGradient></defs>'
            f'<circle cx="{x}" cy="{y}" r="{s*1.25:.0f}" fill="url(#glow{uid})"/>'
            f'<g stroke="{LINE}" stroke-width="2">{edges}{ring}</g>{nodes}'
            f'<circle cx="{x}" cy="{y}" r="{s*0.06:.1f}" fill="{GOLD}"/>')

def lockup(x, y, h, uid):
    sc = h / 512
    return (f'<g transform="translate({x} {y}) scale({sc:.4f})">{mark_inner("sanad-mark", uid)}</g>'
            f'<text x="{x + h*1.12:.0f}" y="{y + h*0.56:.0f}" font-family="{FONT}" font-size="{h*0.42:.0f}" font-weight="600" letter-spacing="-1" fill="{MIST}">Sanad</text>'
            f'<text x="{x + h*1.13:.0f}" y="{y + h*0.88:.0f}" font-family="{FONT}" font-size="{h*0.16:.0f}" font-weight="500" letter-spacing="2" fill="{DIM}">BY EJADAH AI LABS</text>')

def svg(w, h, title, body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="{{{{ALT_TEXT}}}}">\n'
            f'  <title>{title}</title>\n'
            f'  <!-- Template, {w}x{h}. Generated by make-templates.py from the brand tokens. Replace {{{{PLACEHOLDERS}}}}; 64px safe area. -->\n'
            f'  <rect width="{w}" height="{h}" fill="{INK}"/>\n  {body}\n</svg>\n')

def eyebrow(x, y, size=22):
    return f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" font-weight="500" letter-spacing="{size*0.18:.1f}" fill="{BRIGHT}">{{{{EYEBROW}}}}</text>'

def headline(x, y, size, lines=2):
    return "".join(f'<text x="{x}" y="{y + i*size*1.1:.0f}" font-family="{FONT}" font-size="{size}" font-weight="600" letter-spacing="{-size*0.03:.1f}" fill="{MIST}">{{{{HEADLINE_LINE_{i+1}}}}}</text>' for i in range(lines))

def support(x, y, size):
    return f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" fill="{DIM}">{{{{SUPPORTING_LINE}}}}</text>'

def status(x, y, size=20):
    return (f'<circle cx="{x+8}" cy="{y - size*0.35:.0f}" r="7" fill="{BUILT}"/>'
            f'<text x="{x+24}" y="{y}" font-family="{FONT}" font-size="{size}" font-weight="500" fill="{BUILT}">{{{{STATUS: build in progress | planned}}}}</text>')

files = {
  "social-post-1200x627.svg": svg(1200, 627, "Social post",
      eyebrow(64, 120) + headline(64, 200, 60) + support(64, 350, 26) + status(64, 420) +
      graph(960, 300, 150, "sp") + lockup(64, 486, 88, "sp")),
  "og-image-1200x630.svg": svg(1200, 630, "Open Graph image",
      eyebrow(64, 130) + headline(64, 215, 64) + support(64, 370, 26) + graph(960, 300, 150, "og") + lockup(64, 486, 88, "og")),
  "github-social-1280x640.svg": svg(1280, 640, "GitHub social preview",
      lockup(64, 64, 96, "gh") + headline(64, 300, 58) +
      f'<text x="64" y="480" font-family="{MONO}" font-size="24" fill="{DIM}">{{{{REPO_OR_COMMAND, e.g. ejadahailabs/E-REW-support}}}}</text>' + graph(1040, 380, 150, "gh")),
  "linkedin-banner-1584x396.svg": svg(1584, 396, "LinkedIn company banner",
      # LinkedIn covers the bottom-left with the profile logo: keep content right of x=420 on mobile.
      headline(520, 170, 52, 1) + support(520, 230, 26) + graph(1330, 198, 120, "lb")),
  "article-header-1600x840.svg": svg(1600, 840, "Article header",
      eyebrow(96, 200, 24) + headline(96, 300, 80) + support(96, 500, 30) +
      f'<text x="96" y="740" font-family="{FONT}" font-size="22" fill="{MUTED}">{{{{AUTHOR}}}} · {{{{DATE}}}} · ejadahailabs.com/insights</text>' + graph(1290, 400, 190, "ah")),
  "carousel-slide-1080x1350.svg": svg(1080, 1350, "LinkedIn carousel slide",
      f'<text x="64" y="120" font-family="{MONO}" font-size="24" fill="{MUTED}">{{{{N}}}} / {{{{TOTAL}}}}</text>' +
      eyebrow(64, 260, 24) + headline(64, 360, 72, 3) +
      "".join(f'<text x="64" y="{660 + i*64}" font-family="{FONT}" font-size="34" fill="{DIM}">{{{{POINT_{i+1}}}}}</text>' for i in range(4)) +
      status(64, 1000, 26) + f'<line x1="64" y1="1130" x2="1016" y2="1130" stroke="{LINE}" stroke-width="2"/>' + lockup(64, 1170, 112, "cs")),
}
for name, body in files.items():
    (here / name).write_text(body)
print(f"make-templates: wrote {len(files)} files")
